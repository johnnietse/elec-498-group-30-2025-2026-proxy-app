import numpy as np

def print_filtered(data_dict, name):
    print(f"\n--- {name} ---")
    for r, vals in data_dict.items():
        if len(vals) < 4:
            continue
        m, s = np.mean(vals), np.std(vals)
        filtered = [v for v in vals if abs(v-m) < 1.15 * s]
        if len(filtered) < len(vals):
            dropped = set(vals) - set(filtered)
            print(f"N={r}: Dropped {dropped} | Kept {len(filtered)}/{len(vals)}")
        else:
            print(f"N={r}: No outliers dropped.")

